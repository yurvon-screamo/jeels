//! Фазы тренировки руки и исходы ответов юзера.

/// Подфаза тренировки слов. Несловесные карты (кандзи, грамматика) имеют
/// единственное направление и в подфазах не участвуют.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AcquaintanceSubphase {
    /// яп→рус: фронт — японская сторона.
    Forward,
    /// рус→яп: фронт — перевод.
    Reverse,
}

/// Исход одного ответа в тренировке. Единственный источник истины для
/// перерисовки UI (полоса руки, тег фазы): рассинхрон между доменом и
/// отображением невозможен по построению.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AnswerOutcome {
    /// Успех засчитан; `progress` — видимый прогресс карты после ответа.
    Counted { progress: u8 },
    /// Провал: прогресс карты не меняется.
    Failed,
    /// Карта уже закрыла критерий текущей подфазы (слова) либо общий
    /// критерий (несловесные карты): ответы больше не меняют её прогресс.
    ProgressFrozen,
    /// Последняя карта закрыла последний критерий — тренировка завершена.
    /// Смена направления слов сюда не входит: она происходит на границе
    /// витка через `AcquaintanceHand::advance_subphase_if_words_done`,
    /// а не как побочный эффект ответа.
    HandCompleted,
}
